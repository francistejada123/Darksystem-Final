<?php
// modules/settings/backup_download.php
// Streams a full .sql dump of the database — pure PHP (SHOW CREATE TABLE +
// batched INSERTs), no shell_exec/mysqldump dependency since shared
// hosting often disables exec(). Admin only.

require_once __DIR__ . '/../../config/database.php';
require_once __DIR__ . '/../../includes/auth.php';

if (!hasRole('Administrator')) {
    http_response_code(403);
    die('Forbidden');
}

global $db, $dbname;

set_time_limit(120);

$filename = 'egradepro_backup_' . date('Y-m-d_His') . '.sql';
header('Content-Type: application/sql; charset=utf-8');
header('Content-Disposition: attachment; filename="' . $filename . '"');
header('Cache-Control: no-cache, no-store, must-revalidate');

$tables = $db->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);

echo "-- EGRADEPRO Database Backup\n";
echo "-- Database: $dbname\n";
echo "-- Generated: " . date('Y-m-d H:i:s') . "\n";
echo "-- Generated by: " . ($_SESSION['user_name'] ?? $_SESSION['username'] ?? 'Administrator') . "\n\n";
echo "SET NAMES utf8mb4;\n";
echo "SET FOREIGN_KEY_CHECKS = 0;\n";
echo "SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n\n";

foreach ($tables as $table) {
    // --- Structure ---
    echo "-- --------------------------------------------------------\n";
    echo "-- Table structure for `$table`\n";
    echo "-- --------------------------------------------------------\n";
    echo "DROP TABLE IF EXISTS `$table`;\n";

    $create = $db->query("SHOW CREATE TABLE `$table`")->fetch();
    echo $create['Create Table'] . ";\n\n";

    // --- Data (batched INSERTs, 100 rows per statement) ---
    $count_stmt = $db->query("SELECT COUNT(*) FROM `$table`");
    $row_count = (int) $count_stmt->fetchColumn();

    if ($row_count > 0) {
        echo "-- Data for `$table` ($row_count rows)\n";

        $col_stmt = $db->query("SHOW COLUMNS FROM `$table`");
        $columns = array_map(fn($c) => $c['Field'], $col_stmt->fetchAll());
        $col_list = '`' . implode('`, `', $columns) . '`';

        $batch_size = 100;
        $offset = 0;
        $data_stmt = $db->query("SELECT * FROM `$table`");

        $batch = [];
        while ($row = $data_stmt->fetch(PDO::FETCH_NUM)) {
            $values = array_map(function ($v) use ($db) {
                if ($v === null) return 'NULL';
                return $db->quote($v);
            }, $row);
            $batch[] = '(' . implode(', ', $values) . ')';

            if (count($batch) >= $batch_size) {
                echo "INSERT INTO `$table` ($col_list) VALUES\n" . implode(",\n", $batch) . ";\n";
                $batch = [];
                flush();
            }
        }
        if (!empty($batch)) {
            echo "INSERT INTO `$table` ($col_list) VALUES\n" . implode(",\n", $batch) . ";\n";
        }
        echo "\n";
    }
    flush();
}

echo "SET FOREIGN_KEY_CHECKS = 1;\n";

if (function_exists('logActivity')) {
    logActivity($_SESSION['user_id'] ?? null, 'Database Backup Downloaded', 'settings', "Backup of $dbname (" . count($tables) . " tables)");
}
exit;